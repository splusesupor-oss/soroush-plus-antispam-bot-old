def validate_puzzle(question, answer):
    """Reject clues that merely copy a meaningful answer word."""
    import re
    words = set(re.findall(r"[\wآ-ی]+", question.lower()))
    answer_words = set(re.findall(r"[\wآ-ی]+", answer.lower()))
    return bool("+" in question and words.isdisjoint(answer_words))
