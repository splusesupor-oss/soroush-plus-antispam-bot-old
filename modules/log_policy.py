def important_info(text):
    # INFO was historically also used for actual failures. Never hide these,
    # even when a diagnostic prefix happens to match.
    if "result=failed" in text or any(word in text for word in ("FAILED", "ERROR", "OVERFLOW", "TIMEOUT", "DROP", "SHED", "BACKPRESSURE")):
        return True
    if text.startswith("KEEPALIVE PING STATE"):
        return not any("state=" + state in text for state in ("CREATED", "SENT", "RESPONSE", "COMPLETED", "QUEUED", "WRITE"))
    return not text.startswith(NOISY_PREFIXES)
