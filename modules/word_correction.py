_active = {}
_remaining = {}
_tokens = count(1)

def start(chat_id):
    remaining = _remaining.get(chat_id)
    if not remaining:
        remaining = list(range(len(WORDS)))
        _remaining[chat_id] = remaining
    index = random.choice(remaining)
    remaining.remove(index)
    wrong, correct = WORDS[index]
    token = next(_tokens)
    _active[chat_id] = {'wrong': wrong, 'correct': correct, 'token': token}
    return dict(_active[chat_id])

def _letters(value):
    """فقط حروف: فاصله و نیم‌فاصله نادیده گرفته می‌شوند."""
    return (
        str(value or "").strip()
        .replace("\u200c", "").replace("\u200f", "").replace("\u200e", "")
        .replace("ي", "ی").replace("ك", "ک")
        .replace(" ", "")
    )


def _spacing(value):
    """حروف به‌همراه فاصله‌گذاری، با تفکیک نیم‌فاصله از فاصلهٔ معمولی.

    برای جفت‌هایی مثل «هم اکنون» → «هم‌اکنون» تفاوت *فقط* در همین است.
    اگر نیم‌فاصله را با فاصله یکی بگیریم، شکل غلط هم درست شمرده می‌شود و
    بازی غیرقابل‌باخت می‌گردد. پس نیم‌فاصله به نشانهٔ اختصاصی نگاشت
    می‌شود و فقط فاصله‌های تکراری فشرده می‌گردند.
    """
    text = (
        str(value or "").strip()
        .replace("\u200f", "").replace("\u200e", "").replace("\ufeff", "")
        .replace("ي", "ی").replace("ك", "ک")
    )
    text = " ".join(text.split(" "))
    while "  " in text:
        text = text.replace("  ", " ")
    return text.replace("\u200c", "\x00").strip()


def _norm(value):
    """سازگاری با کد قدیمی."""
    return _letters(value)


def answer(chat_id, text):
    """پاسخ را بررسی می‌کند.

    ``None`` یعنی «این پیام به بازی تصحیح کلمات ربطی ندارد» و هندلر باید
    به بازی‌های بعدی اجازهٔ بررسی بدهد. پیش از این هر متنی ``False``
    برمی‌گرداند و چون هندلر روی مقدار غیر-None زودتر return می‌کرد، بازیِ
    فعالِ تصحیح کلمات جلوی «چیستان»، «جای خالی» و بقیه را می‌گرفت.
    """
    data = _active.get(chat_id)
    if not data:
        return None
    if not _letters(text):
        return None

    correct, wrong = data['correct'], data['wrong']
    # وقتی تفاوت غلط و درست فقط در فاصله/نیم‌فاصله است، فاصله‌گذاری بخشی از
    # پاسخ است و نباید نادیده گرفته شود؛ در غیر این صورت آن جفت اصلاً قابل
    # حل نمی‌بود. برای بقیه، فاصله‌گذاری سخت‌گیرانه نیست.
    spacing_matters = _letters(correct) == _letters(wrong)
    if spacing_matters:
        if _spacing(text) == _spacing(correct):
            _active.pop(chat_id, None)
            return True
        if _spacing(text) == _spacing(wrong):
            return False
        return None

    if _letters(text) == _letters(correct):
        _active.pop(chat_id, None)
        return True
    # فقط وقتی «پاسخ غلط» اعلام می‌شود که کاربر واقعاً روی همین کلمه تلاش
    # کرده باشد؛ پیام‌های نامرتبط اصلاً مصرف نمی‌شوند.
    if _letters(text) == _letters(wrong):
        return False
    return None

def get(chat_id):
    return dict(_active[chat_id]) if chat_id in _active else None

def clear(chat_id, token=None):
    data = _active.get(chat_id)
    if data and (token is None or data['token'] == token):
        _active.pop(chat_id, None)
        return True
    return False
