# جایزهٔ برنز هر مرحله (پرداخت از راه API اقتصاد).
REWARD_BRONZE = 4


def total_stages():
    return len(PUZZLES)


def _user_key(user_id):
    return str(user_id)


def _norm(text):
    """یکسان‌سازی برای مقایسه: نیم‌فاصله، فاصله و شکل‌های عربی حروف."""
    return (
        str(text or "").strip().lower()
        .replace("\u200c", "").replace("\u200f", "").replace("\u200e", "")
        .replace("ي", "ی").replace("ك", "ک")
        .replace(" ", "")
    )


def seen_count(user_id):
    """تعداد مرحله‌هایی که این کاربر تا کنون دیده است."""
    return len(_SEEN_BY_USER.get(_user_key(user_id), ()))


def remaining_count(user_id):
    """تعداد مرحله‌های باقی‌مانده برای این کاربر."""
    return max(len(PUZZLES) - seen_count(user_id), 0)


def is_exhausted(user_id):
    """آیا این کاربر همهٔ ۱۲۰ مرحله را دیده است."""
    return remaining_count(user_id) == 0


def current_tier(user_id):
    """نام سطحی که کاربر در آن قرار دارد؛ None اگر همه را دیده باشد."""
    seen = _SEEN_BY_USER.get(_user_key(user_id), set())
    for name, tier in zip(TIER_NAMES, TIERS):
        if any(item[1] not in seen for item in tier):
            return name
    return None


def reset_user(user_id=None):
    """تاریخچهٔ یک کاربر (یا همهٔ کاربران) را پاک می‌کند."""
    if user_id is None:
        _SEEN_BY_USER.clear()
        return
    _SEEN_BY_USER.pop(_user_key(user_id), None)


def reset_all():
    """پاک‌سازی کامل — برای تست و ری‌استارت."""
    _ACTIVE.clear()
    _SEEN_BY_USER.clear()


def is_active(chat_id):
    return chat_id in _ACTIVE


def _pick(seen):
    """اولین سطحی که هنوز مرحلهٔ دیده‌نشده دارد؛ انتخاب تصادفی درون آن."""
    for index, tier in enumerate(TIERS):
        remaining = [item for item in tier if item[1] not in seen]
        if remaining:
            return _RANDOM.choice(remaining), index
    return None, None


def start(chat_id, user_id=None):
    """مرحلهٔ تازه‌ای که این کاربر ندیده است.

    ``None`` یعنی شروع نشد: یا بازی دیگری در همین چت فعال است، یا کاربر
    همهٔ ۱۲۰ مرحله را تمام کرده. برای تفکیک از ``is_exhausted`` استفاده کنید.
    """
    if chat_id in _ACTIVE:
        return None
    if user_id is None:
        user_id = chat_id

    key = _user_key(user_id)
    seen = _SEEN_BY_USER.setdefault(key, set())
    picked, tier_index = _pick(seen)
    if picked is None:
        return None

    emoji, answer, aliases = picked
    seen.add(answer)
    _ACTIVE[chat_id] = {
        "emoji": emoji,
        "answer": answer,
        "aliases": tuple(aliases),
        "token": next(_TOKENS),
        "user_id": user_id,
        "tier": TIER_NAMES[tier_index],
        "stage": len(seen),
    }
    return dict(_ACTIVE[chat_id])


def accepted_answers(state):
    """مجموعهٔ پاسخ‌های پذیرفته برای یک مرحله."""
    values = {_norm(state["answer"])}
    values |= {_norm(alias) for alias in state.get("aliases", ())}
    return {value for value in values if value}


def answer(chat_id, user_id, name, text):
    """پاسخ را بررسی و در صورت درستی مرحله را می‌بندد.

    محافظ‌های ضدسوءاستفاده:
      • کاربری که همهٔ مرحله‌ها را دیده امتیاز نمی‌گیرد، حتی اگر معما را
        شخص دیگری شروع کرده باشد.
      • پاسخ‌دهنده (نه فقط شروع‌کننده) این مرحله را «دیده» ثبت می‌شود تا
        هرگز دوباره همان را نگیرد.
      • فقط پاسخ تعیین‌شده پذیرفته می‌شود؛ هر متن دیگری رد است.
    """
    state = _ACTIVE.get(chat_id)
    if not state:
        return None
    if is_exhausted(user_id):
        return None
    if _norm(text) not in accepted_answers(state):
        return None
    _ACTIVE.pop(chat_id, None)
    _SEEN_BY_USER.setdefault(_user_key(user_id), set()).add(state["answer"])
    # reference یکتا: همین معما برای همین کاربر فقط یک بار سکه می‌دهد.
    _economy_award(
        chat_id, user_id, REWARD_BRONZE,
        reference=f"emoji:{chat_id}:{state['token']}",
        note="حدس ایموجی", name=name,
    )
    return state["answer"]


def finish(chat_id, token=None):
    """پایان مرحله با گارد توکن، تا تایمر دور قبلی دور جدید را نبندد."""
    state = _ACTIVE.get(chat_id)
    if not state or (token is not None and state["token"] != token):
        return None
    _ACTIVE.pop(chat_id, None)
    return state["answer"]
